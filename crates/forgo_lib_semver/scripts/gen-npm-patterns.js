#!/usr/bin/env node
// Print src/npm/patterns.rs: node-semver's regular expressions, as compiled
// by `regex!` in src/npm/regex.rs.
//
//   node scripts/gen-npm-patterns.js <node-semver checkout> <commit> > src/npm/patterns.rs
//
// node-semver builds its patterns from tokens (internal/re.js) and caps
// their repetitions ("safe" patterns); this script prints the patterns
// exactly as node-semver uses them, so they stay byte-for-byte the same.
'use strict'
const path = require('path')
const dir = path.resolve(process.argv[2])
const commit = process.argv[3] || 'unknown'
const { src, safeSrc, t } = require(path.join(dir, 'internal/re.js'))
const { version } = require(path.join(dir, 'package.json'))

// [Rust name, token, use the unbounded source instead of the safe one]
const patterns = [
  ['FULL', 'FULL'],
  ['LOOSE', 'LOOSE'],
  ['COMPARATOR', 'COMPARATOR'],
  ['COMPARATOR_LOOSE', 'COMPARATORLOOSE'],
  ['XRANGE', 'XRANGE'],
  ['XRANGE_LOOSE', 'XRANGELOOSE'],
  ['TILDE', 'TILDE'],
  ['TILDE_LOOSE', 'TILDELOOSE'],
  ['CARET', 'CARET'],
  ['CARET_LOOSE', 'CARETLOOSE'],
  ['HYPHEN_RANGE', 'HYPHENRANGE'],
  ['HYPHEN_RANGE_LOOSE', 'HYPHENRANGELOOSE'],
  ['TILDE_TRIM', 'TILDETRIM'],
  ['CARET_TRIM', 'CARETTRIM'],
  ['STAR', 'STAR'],
  ['GTE0', 'GTE0'],
  ['GTE0_PRE', 'GTE0PRE'],
  ['BUILD', 'BUILD'],
  // Range parsing strips build metadata with the unbounded pattern.
  ['BUILD_STRIP', 'BUILD', true],
  ['PRERELEASE', 'PRERELEASE'],
  ['PRERELEASE_LOOSE', 'PRERELEASELOOSE'],
  ['COERCE', 'COERCE'],
  ['COERCE_FULL', 'COERCEFULL'],
]

const lines = [
  '//! node-semver\'s regular expressions, generated by',
  '//! `scripts/gen-npm-patterns.js` from node-semver ' + version + ' (commit',
  '//! ' + commit + '). Do not edit by hand.',
  '',
  'use super::regex::regex;',
  '',
]
for (const [name, token, unbounded] of patterns) {
  const i = t[token]
  if (i === undefined) throw new Error('no token ' + token)
  const re = unbounded ? src[i] : safeSrc[i]
  if (re.includes('"#')) throw new Error('pattern needs another raw string delimiter')
  lines.push(`regex!(${name} = r#"${re}"#);`)
}
console.log(lines.join('\n'))
